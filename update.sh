#!/usr/bin/env bash
# Regenerate the Homebrew formula for the Proton Drive CLI from Proton's own
# release manifest, AND build an x86_64 Linux *bottle* so `brew install` pours it
# with no C compiler (Homebrew-on-Linux requires one for non-bottled formulae).
# macOS and other arches fall back to the direct-from-Proton url in the formula.
#
# Proton publishes a versioned per-platform binary + a SHA-512 each; Homebrew
# needs a SHA-256, so we download each binary, verify Proton's SHA-512, then
# compute the SHA-256. The Linux binary is repackaged (no compile) into a bottle.
#
# Written for bash 3.2 (no associative arrays) so it runs on stock macOS as well
# as in CI.
#
# Usage: ./update.sh [OUTPUT.rb]     (default: proton-drive-cli.rb)
# Outputs the version on stdout; writes the bottle to $WORK (default ./build).
# Requires: curl, jq, tar, and sha256sum/sha512sum (Linux) or shasum (macOS).
set -euo pipefail

MANIFEST="https://proton.me/download/drive/cli/version.json"
OUT="${1:-proton-drive-cli.rb}"
REPO="jakobhviid/proton-drive-cli-brew" # where the Linux bottle is released
WORK="${WORK:-$(pwd)/build}"

# Linux CI has sha256sum/sha512sum, macOS has shasum. Support both so local
# bumps work.
if command -v sha256sum >/dev/null 2>&1; then
  sha256of() { sha256sum "$1" | cut -d' ' -f1; }
  sha512of() { sha512sum "$1" | cut -d' ' -f1; }
else
  sha256of() { shasum -a 256 "$1" | cut -d' ' -f1; }
  sha512of() { shasum -a 512 "$1" | cut -d' ' -f1; }
fi

json="$(curl -fsSL "$MANIFEST")"
rel="$(jq -c '[.Releases[] | select(.CategoryName=="Stable")][0]' <<<"$json")"
version="$(jq -r '.Version' <<<"$rel")"
[ -n "$version" ] && [ "$version" != "null" ] || { echo "no stable version in manifest" >&2; exit 1; }
echo "Proton Drive CLI — stable $version" >&2

# Download each binary, verify Proton's SHA-512, compute the SHA-256 Homebrew
# needs. Deterministic paths (rather than mktemp) so the bottle step can find
# the linux/x64 binary without a global set from inside a subshell.
DL="${WORK}/dl"
mkdir -p "$DL"

plat_url() { jq -r --arg p "$1" '.Files[] | select(.Platform==$p) | .Url' <<<"$rel"; }

# $1=platform, $2=destination. Verifies Proton's SHA-512, echoes the SHA-256.
fetch_verify() {
  url="$(plat_url "$1")"
  want512="$(jq -r --arg p "$1" '.Files[] | select(.Platform==$p) | .Sha512CheckSum' <<<"$rel")"
  [ -n "$url" ] && [ "$url" != "null" ] || {
    echo "missing $1 in manifest" >&2
    exit 1
  }
  echo "  fetching $1 …" >&2
  curl -fsSL "$url" -o "$2"
  got512="$(sha512of "$2")"
  [ "$got512" = "$want512" ] || {
    echo "SHA-512 mismatch for $1: ${got512} != ${want512}" >&2
    exit 1
  }
  sha256of "$2"
}

URL_MAC_ARM="$(plat_url macos/arm64)"
SHA_MAC_ARM="$(fetch_verify macos/arm64 "${DL}/macos-arm64")"
URL_MAC_X64="$(plat_url macos/x64)"
SHA_MAC_X64="$(fetch_verify macos/x64 "${DL}/macos-x64")"
URL_LNX_ARM="$(plat_url linux/arm64)"
SHA_LNX_ARM="$(fetch_verify linux/arm64 "${DL}/linux-arm64")"
URL_LNX_X64="$(plat_url linux/x64)"
SHA_LNX_X64="$(fetch_verify linux/x64 "${DL}/linux-x64")"
linux_x64_bin="${DL}/linux-x64"

# Build the x86_64_linux bottle: a tar.gz of the keg layout Homebrew would install
# (proton-drive-cli/<version>/bin/proton-drive). No compilation — just repackaging.
mkdir -p "$WORK"
stage="$WORK/stage"
keg="$stage/proton-drive-cli/${version}/bin"
rm -rf "$stage"; mkdir -p "$keg"
mv "$linux_x64_bin" "$keg/proton-drive"
chmod +x "$keg/proton-drive"
bottle="$WORK/proton-drive-cli-${version}.x86_64_linux.bottle.tar.gz"
rm -f "$WORK"/*.bottle.tar.gz
( cd "$stage" && tar czf "$bottle" proton-drive-cli )
rm -rf "$stage" "$DL"
BOTTLE_SHA256="$(sha256of "$bottle")"
echo "  built bottle $(basename "$bottle")" >&2

root_url="https://github.com/${REPO}/releases/download/v${version}"

cat >"$OUT" <<EOF
# Auto-generated by proton-drive-cli-brew from Proton's release manifest.
# Do not edit by hand — run \`update.sh\` (CI keeps it current).
class ProtonDriveCli < Formula
  desc "Access Proton Drive end-to-end encrypted cloud storage from the terminal"
  homepage "https://proton.me/drive"
  version "${version}"
  license "MIT"

  # Proton publishes no tags these URLs could be checked against, so point
  # livecheck at the manifest this formula is generated from. Without it the
  # tap's daily freshness check cannot tell whether this formula has fallen
  # behind Proton.
  livecheck do
    url "${MANIFEST}"
    strategy :json do |json|
      json["Releases"]&.select { |r| r["CategoryName"] == "Stable" }&.map { |r| r["Version"] }
    end
  end

  # Prebuilt x86_64 Linux bottle so \`brew install\` pours it with no C compiler
  # (Homebrew-on-Linux otherwise requires one — a problem on atomic distros).
  # macOS and other arches fall back to the direct-from-Proton url below; macOS
  # always has clang via the required Command Line Tools, so no bottle is needed.
  bottle do
    root_url "${root_url}"
    sha256 cellar: :any_skip_relocation, x86_64_linux: "${BOTTLE_SHA256}"
  end

  on_macos do
    on_arm do
      url "${URL_MAC_ARM}"
      sha256 "${SHA_MAC_ARM}"
    end
    on_intel do
      url "${URL_MAC_X64}"
      sha256 "${SHA_MAC_X64}"
    end
  end

  on_linux do
    # On a headless Linux server there's no Secret Service/libsecret keyring, so
    # the session can be stored in \`pass\` instead (PROTON_DRIVE_CREDENTIALS_STORE
    # — see caveats). Ship it so that path is one env var away, not another install.
    depends_on "pass"

    on_arm do
      url "${URL_LNX_ARM}"
      sha256 "${SHA_LNX_ARM}"
    end
    on_intel do
      url "${URL_LNX_X64}"
      sha256 "${SHA_LNX_X64}"
    end
  end

  # Proton names the binary \`proton-drive\`; keep that so their docs' commands
  # work verbatim. The *formula* is proton-drive-cli to avoid the main app's name.
  def install
    bin.install "proton-drive"
  end

  def caveats
    <<~EOS
      proton-drive keeps its login session in your OS keyring — Keychain on macOS,
      Secret Service/libsecret on Linux. A headless Linux server has no keyring, so
      store the session in \`pass\` (installed as a dependency here) instead:

        gpg --quick-generate-key "proton-drive" default default never
        pass init "proton-drive"
        export PROTON_DRIVE_CREDENTIALS_STORE=pass   # add to your profile / systemd unit

      Sign-in is browser-based, so authenticate once interactively (or on a desktop
      sharing the same pass/GPG key) — then unattended cron/backup runs work.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/proton-drive version")
  end
end
EOF

echo "wrote $OUT (v$version) + $(basename "$bottle")" >&2
echo "$version"
